ds = rasterio.open(dsd)
diffs = []
for p in final:
    try:
        r, c = rowcol(ds.transform, p['lon'], p['lat'])
        if 0 <= r < ds.height and 0 <= c < ds.width:
            v = float(ds.read(1)[r, c])
            if v > -100:
                v = v / 100.0  # DSM 6.30 хранит сантиметры
                p['dsm'] = round(v, 2)
                p['diff'] = round(p['val'] - v, 2)
                diffs.append(p['diff'])
    except Exception:
        pass
print(f'валидация vs DSM 6.30: n={len(diffs)}', end='')
if diffs:
    d = np.array(diffs)
    print(f', bias {d.mean():+.2f} м, MAD {np.median(np.abs(d - d.mean())):.2f} м, p95 {np.percentile(np.abs(d), 95):.2f} м')

