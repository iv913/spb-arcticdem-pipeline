# --- геопривязка ---
geo = json.load(open(f'{OUTD}/../atayanc_6.30/georef_6.30.json')) if False else json.load(open('/home/z/my-project/download/atayanc_6.30/georef_6.30.json'))
a0, b0, c0, d0, e0, f0 = geo['affine_deg']
nw = json.load(open(f'{R30}/nw_affine_6.30.json'))
