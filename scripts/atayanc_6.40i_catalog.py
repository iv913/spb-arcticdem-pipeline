MLAT = 111132.0
M = np.array([[a0, b0], [d0, e0]])
Minv = np.linalg.inv(M)

for p in final:
    px, py = p['px'], p['py']
    isnw = (py < 460 and px < 430) or (py < 660 and px < 260)
    p['nw'] = isnw
    if isnw:
        E = na[0] * px + na[1] * py + na[2]
        Nn = na[3] * px + na[4] * py + na[5]
        p['lon'], p['lat'] = E / MLON, Nn / MLAT
    else:
        lon, lat = M @ np.array([px, py]) + np.array([c0, f0])
        p['lon'], p['lat'] = float(lon), float(lat)

# --- валидация vs DSM 6.30 ---
