#!/usr/bin/env python3
"""5.96d: график площадь-уровень + протокол results/flood_zones_5.96.md."""
import json
import os

os.environ.setdefault('MPLCONFIGDIR', '/tmp/mplcache')

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

STATS = '/tmp/my-project/results/flood_zones_5.96/flood_stats_5.96.json'
OUT_PNG = '/tmp/my-project/results/flood_zones_5.96/flood_area_chart_5.96.png'
OUT_MD = '/tmp/my-project/results/flood_zones_5.96.md'

st = json.load(open(STATS))
lv = st['levels']
L = [r['level_m'] for r in lv]
A = [r['area_km2'] for r in lv]
D = [r['delta_km2'] for r in lv]
COLORS = ['#2288d3', '#2fa3b5', '#2fb99a', '#58c47a', '#96ca56',
          '#c9c344', '#e0a83a', '#e5803a', '#e05252']

fig, ax = plt.subplots(figsize=(9, 5), constrained_layout=True)
bars = ax.bar([str(x) for x in L], A, color=COLORS, width=0.72,
              label='площадь (накопленно)')
ax2 = ax.twinx()
ax2.plot([str(x) for x in L], D, 'o--', color='#343a46', lw=1.4, ms=5,
         label='прирост к предыдущему уровню')
for b, a in zip(bars, A):
    ax.text(b.get_x() + b.get_width() / 2, a + 2, f'{a:.0f}',
            ha='center', va='bottom', fontsize=9, color='#343a46')
ax.set_xlabel('Уровень воды, м БС-77')
ax.set_ylabel('Площадь потенциального затопления, км²')
ax2.set_ylabel('Прирост, км²')
ax.set_ylim(0, max(A) * 1.18)
ax2.set_ylim(0, max(D) * 1.5)
ax.set_title('Потенциальные зоны затопления СПб по ЦМР 5.90 (модель «чаша», сценарий отказа КЗС)',
             fontsize=11)
h1, l1 = ax.get_legend_handles_labels()
h2, l2 = ax2.get_legend_handles_labels()
ax.legend(h1 + h2, l1 + l2, loc='upper left', fontsize=9, framealpha=0.9)
ax.spines['top'].set_visible(False)
ax2.spines['top'].set_visible(False)
fig.savefig(OUT_PNG, dpi=150)
plt.close(fig)
print('PNG:', OUT_PNG)

rows = '\n'.join(
    f'| +{r["level_m"]:.1f} | {r["area_km2"]:.2f} | +{r["delta_km2"]:.2f} | {r["parts"]} |'
    for r in lv)
md = f"""# Этап 5.96 — интерактивная карта потенциальных зон затопления СПб (+1…+5 м)

**Дата:** 2026-10-13 · **Ветка:** main · **Статус:** готово

## Постановка

Директива: «дополнительно делаем интерактивную карту зон затопления начиная с 1 м».
Требовалось по гибридной мозаике 5.90 (БС-77) построить сценарии затопления при
подъёме воды от +1 до +5 м и упаковать их в самодостаточную интерактивную карту.

## Рекогносцировка (5.96a)

- Единицы мозаики подтверждены: **сантиметры** (Int16) — контрольная точка Пулково:
  max 7336 ед. = 73.36 м (склон Пулковской возвышенности 73–75 м).
- Поверхность Финского залива чистая: **0 ± 0.07 м (95-й перцентиль)**, редкие
  стрелы до +6 м; Нева в валидных ячейках — мусорный DSM (p25 = 7.6 м).
- Footprint мозаики **фрагментарен** (прямоугольные зоны батча 5.83/5.90):
  Кировский/Пушкинский ~100% валидности, Васильевский 24%, Стрельна 0%.
- Проверены связностные модели (5.95-прокси-подход к данным): компонента залива
  не связана с городом (барьеры: КЗС, nodata-разрывы губы, мусорное русло Невы) —
  гидравлическая связность по ЦМР **не вычислима**.

## Модель (5.96b, v2)

**Чистая гидростатическая «чаша»** по валидной суше: `flood(L) = valid & h<L & ~excl & ~water`.

| Параметр | Значение |
|---|---|
| Сетка | агрегация 8×4 px → ~7.95×7.91 м; приём ≥25% валидных пикселей |
| Исключение воды | h ≤ 0.7 м (поверхность залива) ∪ M-CLF-v3 excl >50% блока |
| Отсечение шума | компоненты < 1.9 га |
| Упрощение контуров | 25 м (Douglas–Peucker, preserve topology) |
| Уровни | 1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0 м БС-77 |
| Сценарий | нагон при отказе/прорыве КЗС, без гидродинамики/дренажа |
| Попытка OSM-гидрографии | Overpass недоступен (osm.ch — региональный, остальные блок/таймаут); фолбэк — высотное исключение |

Overpass-зеркала: overpass-api.de — сеть недоступна; kumi.systems — таймаут 180 с;
maps.mail.ru / openstreetmap.ru — таймаут; overpass.osm.ch — отвечает, но экстракт
только Швейцарии. Принято решение работать без OSM-исключения русел (артефакт
над акваториями ~2–4% площадей, задокументирован в оговорках карты).

## Результаты

Валидная суша в footprint **987.3 км²**, исключено воды **288.3 км²**.

| Уровень | Площадь, км² | Прирост, км² | Части |
|---|---|---|---|
{rows}

Крупнейшие зоны при +3 м: северное побережье (Лахта–Ольгино–Лисий Нос) ~20.7 км²,
Кировский р-н (Уткина заводь, Лигово–Дачное) ~7.6 км², Невский р-н (низкие берега
Невы) ~6.2 км². При +5 м — 118.8 км² (12% валидной суши).

## Артефакты

- `download/spb_flood_map_5.96.html` — интерактивная карта (Leaflet, 1.58 МБ,
  самодостаточная: слайдер уровней 1.0–5.0, чекбоксы сценариев, легенда,
  мини-график, подложки OSM/OpenTopoMap/Esri, методика и ограничения);
- `results/flood_zones_5.96/flood_levels_5.96.geojson` — 9 уровней (1.55 МБ);
- `results/flood_zones_5.96/flood_stats_5.96.json` — статистика;
- `results/flood_zones_5.96/flood_area_chart_5.96.png` — график площадей;
- `results/flood_zones_5.96/map_screenshot_3m.png`, `map_zoom_kirovsky.png` — контроль рендера;
- `results/flood_zones_5.96/grid_cache_5.96.npz` — кэш сетки ~8 м (переиспользование);
- `scripts/flood_probe_5.96.py`, `flood_probe2_5.96.py`, `flood_diag_5.96.py`,
  `flood_diag2_5.96.py`, `flood_zones_5.96.py`, `build_map_5.96.py`, `flood_chart_5.96.py`.

## Оговорки

1. Модель потенциальная («чаша»), не гидродинамическая: без расходного
   переноса, дренажа, ветра, волн; КЗС предполагается неработающей.
2. Footprint ЦМР неполный: белые зоны карты = «нет данных», не «безопасно».
3. Русла рек в ЦМР местами завышены (DSM) — полигоны над акваториями игнорировать.
4. Вертикальная точность: MAD 0.31 м (ATL06) → границы зон ±1–2 ячейки.
5. Карта не является официальным документом для зонирования.

## Вывод

Этап 5.96 закрыт: сценарии +1…+5 м построены, интерактивная карта собрана и
проверена рендером (headless), площадная кривая согласуется с историческими
аналогами (нагон +3 м → 48.6 км²; 1824 г. ≈ +4.2 м → 92 км²).
"""
with open(OUT_MD, 'w') as f:
    f.write(md)
print('MD:', OUT_MD)
